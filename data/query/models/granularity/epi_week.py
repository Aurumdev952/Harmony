'''WHO epi week of year without JavaScript.

The `epi_week_of_year` granularity groups by the epi week a day falls in,
rendered as `2999-12-30T00:00:00.000Z` plus seven days per week. An epi year
starts on the Monday of the week holding 4 January. Days count from their
calendar year's start, except that 29 to 31 December count from the next year's
start once they reach it, so 1 to 3 January that still sit in the previous epi
year come out as week -1 (`2999-12-23`).

That value depends only on the month and the ISO week number, so a `timeFormat`
extraction to `MM-ww` cascaded into this map reproduces it. The map holds every
(month, ISO week) pair the Gregorian calendar produces. WP-8a proved it equal to
the JavaScript extraction it replaced on every day from 1900 to 2100 in Druid
0.23, and to a port of that JavaScript over a full 400-year cycle
(tests/druid/test_epi_week_native.py).
'''

